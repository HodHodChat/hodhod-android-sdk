#!/usr/bin/env python3
"""Hodhod widget i18n JSON -> Android string resources.

Reads chatwoot/app/javascript/widget/i18n/locale/{en,fa,ar,de,es,fr}.json and writes
hodhod-ui/src/main/res/values[-xx]/hodhod_strings.xml so the SDK stays in sync with the web widget.

Rules
  * key path  A.B.C            -> resource  hodhod_a_b_c
  * "x | y"   (vue-i18n plural) -> <plurals> (one = x, other = y; extra CLDR quantities of ar copy `other`)
  * {name}                      -> positional %N$s ; {n}/{count}/{min}... in plurals -> %N$d.
                                   Positional index = alphabetical order of the placeholder names in the
                                   ENGLISH string, so every locale uses the same argument order
                                   (e.g. {a} {b} -> getString(id, a, b)). Documented in README.
  * English is the default (res/values); other locales only contain keys they translate
    (missing ones fall back to English automatically, `tools:ignore=MissingTranslation`).

Usage:  python3 tools/gen_strings.py [--src <locale dir>] [--out <res dir>]
The generated hodhod_strings.xml files are COMMITTED; this script is a maintainer tool and is NOT part of the
Gradle build (a clean checkout builds without the Rails tree).
"""
import argparse, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_SRC = os.path.normpath(os.path.join(ROOT, '..', 'chatwoot', 'app', 'javascript', 'widget', 'i18n', 'locale'))
DEFAULT_OUT = os.path.join(ROOT, 'hodhod-ui', 'src', 'main', 'res')
LOCALES = ['en', 'fa', 'ar', 'de', 'es', 'fr']
PH = re.compile(r'\{([A-Za-z_][A-Za-z0-9_]*)\}')
NUMERIC = {'n', 'count', 'min', 'hours', 'minutes'}
AR_QTY = ['zero', 'one', 'two', 'few', 'many', 'other']


def flatten(obj, prefix=''):
    for k, v in obj.items():
        key = f'{prefix}_{k}' if prefix else k
        if isinstance(v, dict):
            yield from flatten(v, key)
        elif isinstance(v, str):
            yield key, v


def res_name(key):
    return 'hodhod_' + re.sub(r'[^a-z0-9_]', '_', key.lower())


def esc(s):
    s = s.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"')
    s = s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    s = s.replace('%', '%%').replace('@', '\\@').replace('\n', '\\n')
    if s.startswith('?'):
        s = '\\' + s
    return s


def convert(text, order, plural):
    """escape + replace placeholders with positional format args."""
    out = esc(text)
    def sub(m):
        name = m.group(1)
        if name not in order:
            order.append(name)
        idx = order.index(name) + 1
        conv = 'd' if (plural and name in NUMERIC) else 's'
        return f'%{idx}${conv}'
    # placeholders contain only [A-Za-z0-9_{}] so escaping above leaves them intact
    return PH.sub(sub, out)


def en_order(text):
    return sorted(set(PH.findall(text)))


def is_plural(text):
    return ' | ' in text


def build(locale, data, en_flat):
    flat = dict(flatten(data))
    for k, tr in OVERRIDE.items():
        if locale in tr:
            flat[k] = tr[locale]
    for k, tr in SUPPLEMENT.items():
        if k not in flat and locale in tr:
            flat[k] = tr[locale]
    missing = [k for k in en_flat if k not in flat]
    if missing:
        print(f'[gen_strings] WARNING {locale}: missing {missing} -> English fallback', file=sys.stderr)
        for k in missing:
            flat[k] = en_flat[k]
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- GENERATED by tools/gen_strings.py from the web widget i18n locale JSON. DO NOT EDIT. -->',
             '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation,ExtraTranslation,PluralsCandidate,TypographyEllipsis,Typos,ImpliedQuantity,UnusedResources">']
    for key in en_flat:
        if key not in flat:
            continue
        val = flat[key]
        order = en_order(en_flat[key])
        # placeholders only present in the translation get appended deterministically
        for p in sorted(set(PH.findall(val))):
            if p not in order:
                order.append(p)
        name = res_name(key)
        if is_plural(en_flat[key]) or is_plural(val):
            forms = [f.strip() for f in val.split(' | ')]
            one = forms[0]
            other = forms[-1] if len(forms) > 1 else forms[0]
            qty = {'one': one, 'other': other}
            if locale == 'ar':
                for q in AR_QTY:
                    qty.setdefault(q, other)
            elif locale in ('es', 'fr'):
                qty.setdefault('many', other)
            lines.append(f'    <plurals name="{name}">')
            for q in ['zero', 'one', 'two', 'few', 'many', 'other']:
                if q in qty:
                    lines.append(f'        <item quantity="{q}">{convert(qty[q], list(order), True)}</item>')
            lines.append('    </plurals>')
        else:
            lines.append(f'    <string name="{name}">{convert(val, list(order), False)}</string>')
    lines.append('</resources>')
    return '\n'.join(lines) + '\n'


