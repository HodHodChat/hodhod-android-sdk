def build_extra(locale):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- GENERATED by tools/gen_strings.py (EXTRA table). DO NOT EDIT. -->',
             '<resources>']
    for name, tr in EXTRA.items():
        lines.append(f'    <string name="{name}">{convert(tr[locale], en_order(tr["en"]), False)}</string>')
    lines.append('</resources>')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', default=DEFAULT_SRC)
    ap.add_argument('--out', default=DEFAULT_OUT)
    ap.add_argument('--check', action='store_true', help='fail if output would change')
    a = ap.parse_args()
    if not os.path.isdir(a.src):
        print(f'[gen_strings] source {a.src} not found; keeping committed strings', file=sys.stderr)
        return 0
    en_flat = dict(flatten(json.load(open(os.path.join(a.src, 'en.json'), encoding='utf-8'))))
    changed = 0
    for loc in LOCALES:
        data = json.load(open(os.path.join(a.src, f'{loc}.json'), encoding='utf-8'))
        xml = build(loc, data, en_flat)
        d = os.path.join(a.out, 'values' if loc == 'en' else f'values-{loc}')
        os.makedirs(d, exist_ok=True)
        p = os.path.join(d, 'hodhod_strings.xml')
        old = open(p, encoding='utf-8').read() if os.path.exists(p) else None
        if old != xml:
            changed += 1
            if not a.check:
                open(p, 'w', encoding='utf-8').write(xml)
        px = os.path.join(d, 'hodhod_ui_strings.xml')
        xx = build_extra(loc)
        if (open(px, encoding='utf-8').read() if os.path.exists(px) else None) != xx:
            changed += 1
            if not a.check:
                open(px, 'w', encoding='utf-8').write(xx)
        print(f'[gen_strings] {loc}: {xml.count("<string ")} strings, {xml.count("<plurals ")} plurals')
    if a.check and changed:
        print('[gen_strings] out of date', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
